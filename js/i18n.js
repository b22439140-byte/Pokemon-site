const I18N_STORAGE_KEY = 'pokevault-lang';
const I18N_DEFAULT = 'nl';

function getLang() {
    try {
        const saved = localStorage.getItem(I18N_STORAGE_KEY);
        if (saved === 'nl' || saved === 'en') return saved;
    } catch (_) { /* ignore */ }
    return I18N_DEFAULT;
}

function t(key, vars) {
    const lang = getLang();
    const dict = I18N_STRINGS[lang] || I18N_STRINGS.nl;
    let str = dict[key];
    if (str == null) {
        str = I18N_STRINGS.nl[key];
    }
    if (str == null) return key;
    if (vars && typeof vars === 'object') {
        str = String(str).replace(/\{(\w+)\}/g, (_, name) =>
            vars[name] != null ? String(vars[name]) : `{${name}}`
        );
    }
    return str;
}

function applyI18n(root) {
    const scope = root || document;

    scope.querySelectorAll('[data-i18n]').forEach((el) => {
        const key = el.getAttribute('data-i18n');
        if (!key) return;
        el.textContent = t(key);
    });

    scope.querySelectorAll('[data-i18n-html]').forEach((el) => {
        const key = el.getAttribute('data-i18n-html');
        if (!key) return;
        el.innerHTML = t(key);
    });

    scope.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        const key = el.getAttribute('data-i18n-placeholder');
        if (!key) return;
        el.setAttribute('placeholder', t(key));
    });

    scope.querySelectorAll('[data-i18n-aria]').forEach((el) => {
        const key = el.getAttribute('data-i18n-aria');
        if (!key) return;
        el.setAttribute('aria-label', t(key));
    });

    const titleEl = document.querySelector('title[data-i18n-title]');
    if (titleEl) {
        const key = titleEl.getAttribute('data-i18n-title');
        if (key) document.title = t(key);
    }
}

function updateLangButtons() {
    const lang = getLang();
    document.querySelectorAll('.lang-btn[data-set-lang]').forEach((btn) => {
        btn.setAttribute('aria-pressed', btn.getAttribute('data-set-lang') === lang ? 'true' : 'false');
    });
    const group = document.querySelector('.lang-switch');
    if (group) group.setAttribute('aria-label', t('lang.aria'));
}

function setLang(lang) {
    if (lang !== 'nl' && lang !== 'en') return;
    try {
        localStorage.setItem(I18N_STORAGE_KEY, lang);
    } catch (_) { /* ignore */ }
    document.documentElement.lang = lang;
    applyI18n(document);
    updateLangButtons();
    window.dispatchEvent(new CustomEvent('pokevault:langchange', { detail: { lang } }));
}

function resolveButtonLabel(label) {
    if (!label || label === 'In winkelwagen' || label === 'Add to cart') return t('btn.addToCart');
    if (label === 'Neem contact op' || label === 'Contact us') return t('btn.contact');
    if (label === 'Pre-order') return t('badge.preorder');
    return label;
}

document.addEventListener('DOMContentLoaded', () => {
    const lang = getLang();
    document.documentElement.lang = lang;
    applyI18n(document);
    updateLangButtons();

    document.querySelectorAll('.lang-btn[data-set-lang]').forEach((btn) => {
        btn.addEventListener('click', () => {
            const next = btn.getAttribute('data-set-lang');
            if (next && next !== getLang()) setLang(next);
        });
    });
});

window.t = t;
window.getLang = getLang;
window.setLang = setLang;
window.applyI18n = applyI18n;
window.resolveButtonLabel = resolveButtonLabel;
window.I18N_STRINGS = I18N_STRINGS;
